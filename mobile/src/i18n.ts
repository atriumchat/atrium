export type Key = WebKey | keyof typeof extra.ru;

const dictionaries = { ru: { ...ru, ...extra.ru } as Record<string, Entry>, en: { ...en, ...extra.en } as Record<string, Entry> };
// Hermes has no Intl.PluralRules: the two languages' cardinal rules by hand.
const plurals = {
  ru: { select: (n: number): Intl.LDMLPluralRule => { const a = Math.abs(n); const m10 = a % 10, m100 = a % 100; return Number.isInteger(a) ? (m10 === 1 && m100 !== 11 ? 'one' : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? 'few' : 'many') : 'other'; } },
  en: { select: (n: number): Intl.LDMLPluralRule => (n === 1 ? 'one' : 'other') },
};
const KEY = 'gomex.lang';

const system = (): Lang => (getLocales()[0]?.languageCode === 'ru' ? 'ru' : 'en');
/** `choice` is what the person picked (null = follow the device). */
export const useLanguage = create<{ lang: Lang; choice: Lang | null }>(() => ({ lang: system(), choice: null }));
SecureStore.getItemAsync(KEY).then((saved) => { if (saved === 'ru' || saved === 'en') useLanguage.setState({ lang: saved, choice: saved }); }, () => undefined);
export function setLanguage(choice: Lang | null) {
  useLanguage.setState({ lang: choice ?? system(), choice });
  (choice ? SecureStore.setItemAsync(KEY, choice) : SecureStore.deleteItemAsync(KEY)).catch(() => undefined);
}

export const localeOf = (lang: Lang = useLanguage.getState().lang) => (lang === 'ru' ? 'ru-RU' : 'en-US');

function translate(lang: Lang, key: Key, params?: Params): string {
  const entry = dictionaries[lang][key] ?? dictionaries.ru[key] ?? key;
  let text: string;
  if (typeof entry === 'string') text = entry;
  else text = entry[plurals[lang].select(Number(params?.n ?? 0))] ?? entry.other;
  return params ? text.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m)) : text;
}
export type TFn = (key: Key, params?: Params) => string;
/** Outside React (stores, socket handlers). */
export const t: TFn = (key, params) => translate(useLanguage.getState().lang, key, params);
/** In components: re-renders on a language change. */
export function useT(): { t: TFn; lang: Lang } {
  const lang = useLanguage((s) => s.lang);
  return { t: (key, params) => translate(lang, key, params), lang };
}
