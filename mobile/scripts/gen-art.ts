// Regenerates src/art.generated.ts from the web's illustrations (web/src/ui/Illustrations.tsx), whose geometry is
// computed by web/src/ui/iso.ts. Run after the web drawings change: `npx tsx scripts/gen-art.ts`.
import { writeFileSync } from 'node:fs';
import { ART } from '../../web/src/ui/Illustrations';

const out = `// Generated by scripts/gen-art.ts from web/src/ui/Illustrations.tsx. Do not edit.
export type Mark = { d: string; plate?: boolean; ink?: boolean; even?: boolean; o?: number; dash?: string; w?: number };
export type Drawing = { marks: Mark[]; box: [number, number, number, number] };
export const ART = ${JSON.stringify(Object.fromEntries(Object.entries(ART).map(([k, v]) => [k, { box: v.box, marks: v.marks.map(({ cls: _cls, ...m }) => m) }])))} satisfies Record<string, Drawing>;
export type ArtName = keyof typeof ART;
`;
writeFileSync(new URL('../src/art.generated.ts', import.meta.url), out);
