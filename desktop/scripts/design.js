// `npm run design`: brings the web's design layer (DESIGN.md) into the app's own pages (onboarding.html), which are
// local files under a strict CSP and can't load the web's modules:
// - tokens.css: the design tokens (web/src/tokens.ts) as --gx- CSS variables, the same CSS the web's applyTokens makes;
// - flow.css: the flow look's classes, web/src/ui/flow/flow.css as it is.
// Run it after changing either; check:design fails while they're out of date. The types are stripped with rolldown,
// which the web has (through Vite): install the web's packages first.
const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');

const { transformSync } = createRequire(path.join(__dirname, '../../web/package.json'))('rolldown/experimental');

async function main() {
  const file = path.join(__dirname, '../../web/src/tokens.ts');
  const { code, errors } = transformSync(file, fs.readFileSync(file, 'utf8'), { lang: 'ts' });
  if (errors.length) throw new Error(errors.map((e) => e.message).join('\n'));
  const tokens = await import(`data:text/javascript,${encodeURIComponent(code)}`);

  const flow = fs.readFileSync(path.join(__dirname, '../../web/src/ui/flow/flow.css'), 'utf8');
  const files = {
    'tokens.css': `/* Generated by scripts/design.js from web/src/tokens.ts: change the tokens there, then npm run design. */\n${tokens.tokenCss()}\n`,
    'flow.css': `/* Copied by scripts/design.js from web/src/ui/flow/flow.css: change it there, then npm run design. */\n${flow}`,
  };
  const stale = [];
  for (const [name, css] of Object.entries(files)) {
    const out = path.join(__dirname, '..', name);
    const now = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (now === css) continue;
    if (process.argv.includes('--check')) stale.push(name);
    else fs.writeFileSync(out, css);
  }
  if (stale.length) {
    console.error(`${stale.join(', ')} out of date: npm run design`);
    process.exit(1);
  }
  console.log(process.argv.includes('--check') ? 'design ok' : 'tokens.css and flow.css written');
}
main();
