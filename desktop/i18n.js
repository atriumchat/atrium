  let lang = 'en';

  /** ru* → Russian; anything else → English. */
  function pick(locale) {
    return /^ru\b/i.test(String(locale ?? '')) ? 'ru' : 'en';
  }

  function setLang(next) {
    lang = next === 'ru' ? 'ru' : 'en';
    return lang;
  }

  /** The text for `key` in the current language; {name} placeholders take their values from `vars`. */
  function t(key, vars) {
    const text = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
    return vars ? text.replace(/\{(\w+)\}/g, (whole, name) => (name in vars ? String(vars[name]) : whole)) : text;
  }

  const api = { STRINGS, pick, setLang, getLang: () => lang, t };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  // Pages read it from here: a plain <script>, and desktop/ui's bundle, which may wrap this file as CommonJS.
  globalThis.atriumI18n = api;
